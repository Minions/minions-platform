#!/usr/bin/env node
import { createWriteStream } from 'fs';
import { readdir, stat } from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';
import archiver from 'archiver';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ADMIN_CLAUDE_SETTINGS = JSON.stringify({
  enabledPlugins: {
    'playwright@claude-plugins-official': true,
  },
}, null, 2) + '\n';

const ADMIN_CLAUDE_MD = `# Admin Area

This is the lair admin area. Launch Claude Code here to configure and manage the lair using Cabinet's MCP tools.

## Prerequisites

Cabinet must be running before opening a Claude session here:

\`\`\`
# From the lair root
tools/cabinet
\`\`\`

## Available MCP Tools

Cabinet writes \`.mcp.json\` here automatically on every startup, pointing at
its current port. Two MCP endpoints are configured:

**\`cabinet-lair\`** — Lair management tools:
- \`wings\` — Create, list, update, and delete wings
- \`archives\` — Manage git repositories (work, info, private)
- \`costumes\` — Install and remove costumes from the closet
- \`registry\` — Configure costume registries
- \`lair_get_state\` — Read current lair state (wings, repos, costumes)

**\`cabinet-conductor\`** — Workflow tools:
- \`movement\` — Branch management and git commits
- \`plan\` — Hierarchical planning across wings
- \`missions\` — List and launch costume-provided missions
- \`ask\` — Post questions to the overlord (blocking/non-blocking)

## Common Tasks

**Create a new wing:**
Ask Claude to use the \`wings\` tool with \`action=create\`.

**Add a repository:**
Ask Claude to use the \`archives\` tool with \`action=add\`.

**Install a costume:**
Ask Claude to use the \`costumes\` tool with \`action=install\`.

## Port Configuration

\`.mcp.json\` is regenerated by Cabinet on every launch from \`cabinet.config.json\`
at the lair root, so it always points at the port Cabinet is actually running
on — no manual updates needed.
`;

async function createLairPackage() {
  const distDir = path.resolve(__dirname, '../dist');
  const outputZip = path.resolve(__dirname, '../dist/new_lair.zip');

  // Directories to create in the lair structure
  const lairDirs = [
    'new_lair/wings',
    'new_lair/closet',
    'new_lair/info',
    'new_lair/work',
    'new_lair/private',
    'new_lair/tools/runtime',
  ];

  console.log('Creating new_lair.zip package...');

  const output = createWriteStream(outputZip);
  const archive = archiver('zip', { zlib: { level: 9 } });

  const archiveComplete = new Promise((resolve, reject) => {
    output.on('close', resolve);
    archive.on('error', reject);
  });

  archive.pipe(output);

  // Add empty directories with .gitkeep files
  for (const dir of lairDirs) {
    if (!dir.includes('runtime')) {
      archive.append('', { name: `${dir}/.gitkeep` });
    }
  }

  // Add dist folder contents to new_lair/tools/runtime/
  const distFiles = await readdir(distDir, { withFileTypes: true });
  for (const entry of distFiles) {
    // Skip the zip file itself and dev-only sourcemaps — they're only
    // useful for debugging a local build and roughly double the package
    // size for something a shipped runtime never reads.
    if (entry.name === 'new_lair.zip') continue;
    if (entry.name.endsWith('.map')) continue;

    const fullPath = path.join(distDir, entry.name);
    if (entry.isDirectory()) {
      archive.directory(fullPath, `new_lair/tools/runtime/${entry.name}`);
    } else {
      archive.file(fullPath, { name: `new_lair/tools/runtime/${entry.name}` });
    }
  }

  // Add admin area with documentation. No .mcp.json is shipped here —
  // Cabinet writes it on every startup so it always has the correct port.
  archive.append(ADMIN_CLAUDE_SETTINGS, { name: 'new_lair/admin/.claude/settings.json' });
  archive.append(ADMIN_CLAUDE_MD, { name: 'new_lair/admin/CLAUDE.md' });

  await archive.finalize();
  await archiveComplete;

  const zipStats = await stat(outputZip);
  const sizeMB = (zipStats.size / 1024 / 1024).toFixed(2);
  console.log(`✓ new_lair.zip created (${sizeMB} MB)`);
}

createLairPackage().catch((error) => {
  console.error('Failed to create lair package:', error);
  process.exit(1);
});
